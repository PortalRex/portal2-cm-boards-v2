#!/usr/bin/env python3
"""Turn a WR history write-up (one list per map) into SQL that fills old_wrs.

The input is a JSON object of map title -> the lines of that map's write-up, e.g. Silly Noodle's
Portal 2 single player WR history docs (2011 onward), one record per line:

  2012-07-01, 18:44:00 Pocky - Portal Gun - 25.58
  2011-10-08, 00:00:00 Kingpin - Portal Gun - 29.03          (00:00:00: only the day is known)
  2011-12-??, 00:00:00 Blumenrocker - Neurotoxin Sabotage - 1:07.56   (only the month)
  2021-01-16, 00:03:01 Rex - Dual Lasers - 11.16 * (no demo)  (a note after the time)

Lines that aren't records (routing history, notes) are ignored; records without a date or a time
("????") are listed on stderr and left out.

The SQL is self-contained and safe to run again. It adds a record only when the boards don't
already have it (an unbanned run on the map with the same time, by the same player or within a few
days of its date: the boards' oldest dates are sometimes off by weeks), and never one matching a
banned run there or noted as having no demo: a run the boards removed stays removed. It ends by listing what it skipped for those reasons.

Usage:
  python old_wrs.py docs.json --source "Silly Noodle's WR history docs" > old_wrs.sql
  psql "$DATABASE_URL" -f old_wrs.sql
"""
import argparse
import json
import re
import sys

RECORD = re.compile(
    r'^(?P<date>\d{4}-\d{2}-(?:\d{2}|\?\?))(?:[,\s]*(?P<time>\d{2}:\d{2}:\d{2}))?\s+'
    r'(?P<who>.+?)\s+-\s+(?P<map>.+?)\s+-?\s*(?P<score>(?:\d+:)?\d+\.\d{2})(?P<note>\s.*)?$'
)
UNDATED = re.compile(r'^\?+\s+.+\s-\s.+\s-\s')
# A board run with a record's time is the same run when it's on about the same day, or by the same
# player (their name here then or now).
SAME_RUN = (
    'cl.timestamp IS NULL OR abs(cl.timestamp::date - i.set_at::date) <= 3'
    ' OR lower(i.player_name) IN (lower(u.board_name), lower(u.steam_name))'
)


def centis(score):
    minutes, _, rest = score.rpartition(':')
    seconds, cs = rest.split('.')
    return (int(minutes or 0) * 60 + int(seconds)) * 100 + int(cs)


def normalise(line):
    # A stray character where a dash was lost ("2014-09�09").
    return re.sub(r'^(\d{4}-\d{2})[^\d\s?-](\d{2})', r'\1-\2', line.strip())


def parse(title, lines):
    """The map's records, and the lines that look like records but couldn't be used."""
    records, unusable = [], []
    for raw in lines:
        line = normalise(raw)
        m = RECORD.match(line)
        if not m:
            if UNDATED.match(line):
                unusable.append(line)
            continue
        if m['map'].strip().lower() != title.lower():
            unusable.append(line)
            continue
        day = m['date']
        month_only = day.endswith('??')
        time = m['time'] or '00:00:00'
        hour = int(time[:2])
        time_known = not month_only and time != '00:00:00' and hour < 24
        records.append({
            # Without a time, noon UTC: the day is then the same day for viewers everywhere. Only a
            # month: its middle.
            'set_at': f"{day[:8]}15 12:00:00" if month_only else f"{day} {time if time_known else '12:00:00'}",
            'time_known': time_known,
            'date_estimated': month_only,
            'player': m['who'].strip(),
            'score': centis(m['score']),
            'note': (m['note'] or '').strip(' *()') or None,
        })
    return records, unusable


def sql_text(value):
    return 'NULL' if value is None else "'" + value.replace("'", "''") + "'"


def build_sql(records_by_map, source):
    rows = []
    for title, records in records_by_map.items():
        for r in records:
            rows.append(
                f"({sql_text(title)}, {r['score']}, '{r['set_at']}', {str(r['time_known']).lower()}, "
                f"{str(r['date_estimated']).lower()}, {sql_text(r['player'])}, {sql_text(r['note'])})"
            )
    values = ',\n'.join(rows)
    return f"""-- Generated by db/dbscript/old_wrs.py; safe to run again.
BEGIN;
CREATE TEMP TABLE old_wrs_in (
    map_title text, score integer, set_at timestamp, time_known boolean, date_estimated boolean,
    player_name text, note text
) ON COMMIT DROP;
INSERT INTO old_wrs_in VALUES
{values};

-- Each record's Portal 2 map, and whether a run on the boards is the same one (same time, by the
-- same player or on about the same day) or a banned run is.
CREATE TEMP TABLE old_wrs_matched ON COMMIT DROP AS
SELECT i.*, m.steam_id AS map_id,
    EXISTS (
        SELECT 1 FROM changelog AS cl LEFT JOIN users AS u ON u.profile_number = cl.profile_number
        WHERE cl.map_id = m.steam_id AND cl.score = i.score AND NOT cl.banned AND ({SAME_RUN})
    ) AS on_boards,
    EXISTS (
        SELECT 1 FROM changelog AS cl LEFT JOIN users AS u ON u.profile_number = cl.profile_number
        WHERE cl.map_id = m.steam_id AND cl.score = i.score AND cl.banned AND ({SAME_RUN})
    ) AS banned_on_boards
FROM old_wrs_in AS i
LEFT JOIN maps AS m ON lower(m.name) = lower(i.map_title)
    AND m.chapter_id IN (SELECT id FROM chapters WHERE game_id = 1);

INSERT INTO old_wrs (map_id, score, set_at, time_known, date_estimated, player_name, note, source)
SELECT map_id, score, set_at, time_known, date_estimated, player_name, note, {sql_text(source)}
FROM old_wrs_matched
WHERE map_id IS NOT NULL AND NOT on_boards AND NOT banned_on_boards
  AND coalesce(note, '') NOT ILIKE '%no demo%'
ON CONFLICT DO NOTHING;

-- Left out on purpose, for a person to look at.
SELECT map_title, player_name, score, set_at::date AS day, note,
    CASE WHEN map_id IS NULL THEN 'unknown map'
         WHEN banned_on_boards THEN 'banned on the boards'
         ELSE 'no demo' END AS skipped
FROM old_wrs_matched
WHERE map_id IS NULL OR (NOT on_boards AND (banned_on_boards OR coalesce(note, '') ILIKE '%no demo%'))
ORDER BY map_title, set_at;
COMMIT;
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('docs', help='JSON: map title -> the lines of its WR history')
    ap.add_argument('--source', required=True, help='Where the records come from (kept with each record)')
    args = ap.parse_args()

    with open(args.docs, encoding='utf-8') as f:
        docs = json.load(f)
    records_by_map = {}
    for name, lines in docs.items():
        title = re.sub(r'^\d+\s*-\s*', '', name)  # "03 - Portal Gun" -> "Portal Gun"
        records, unusable = parse(title, lines)
        records_by_map[title] = records
        for line in unusable:
            print(f'left out ({title}): {line}', file=sys.stderr)
    total = sum(len(r) for r in records_by_map.values())
    print(f'{total} dated records on {len(records_by_map)} maps', file=sys.stderr)
    sys.stdout.write(build_sql(records_by_map, args.source))


if __name__ == '__main__':
    main()
